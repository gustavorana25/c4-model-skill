def lang_of(doc) -> str:
    """Idioma do documento; desconhecido ou ausente vira pt-BR (a validação avisa)."""
    lang = doc.get("lang") if isinstance(doc, dict) else None
    return lang if lang in MESSAGES else DEFAULT_LANG


def msg(lang: str, key: str, **kw) -> str:
    text = MESSAGES.get(lang, MESSAGES[DEFAULT_LANG]).get(key) or MESSAGES[DEFAULT_LANG][key]
    return text.format(**kw) if kw else text
